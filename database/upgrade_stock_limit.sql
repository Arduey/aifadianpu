-- 爱发电铺 · 商户发货 / 链接发货「限购总量」
-- 语义：0 = 不限量；> 0 = 可售数量 = stock_limit − 已付款订单数（卖完即缺货）
-- 卡密型商品不用此字段（走卡密真实库存）。
-- 执行顺序：先 ALTER（本文件）→ 再重启后端。
-- ══════════════════════════════════════════════════════════════

ALTER TABLE products
  ADD COLUMN stock_limit INT NOT NULL DEFAULT 0 COMMENT '限购总量:0=不限量;>0=可售数量上限(商户发货/链接发货用)';
